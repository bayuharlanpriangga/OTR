// OTR — Generate supabase/migrations/0002_seed_system_data.sql
// Dev-only, bukan bagian app yang di-deploy (sama seperti
// scripts/supabase-smoke-test.mjs). Dijalankan sekali secara manual untuk
// meng-generate file migration dari data/tarot-cards.js dan
// data/default-spreads.js — bukan dijalankan tiap build (data source tetap
// file .js di data/, migration SQL ini cuma "snapshot" hasil generate-nya).
//
// Kenapa dibutuhkan (gap yang ditemukan sesi ini, di luar Roadmap Phase 12
// yang eksplisit): readings.spread_id dan reading_cards.card_id di
// 0001_init_schema.sql adalah foreign key ke spreads(id)/tarot_cards(id).
// Tanpa baris sistem (is_system=true) di kedua tabel itu, SETIAP insert ke
// readings/reading_cards akan gagal FK constraint — termasuk migrasi guest
// data di Phase 13 (guest reading pasti mereferensikan salah satu dari 10
// default spread + kartu dari 78 tarot_cards). 0001 sengaja tidak menyeed
// data ini (fokusnya cuma DDL + RLS), jadi migration terpisah ini yang
// mengisinya.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const { TAROT_CARDS } = await import(path.join(root, "data/tarot-cards.js"));
const { DEFAULT_SPREADS } = await import(path.join(root, "data/default-spreads.js"));

function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlJSON(value) {
  return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
}

function slugFromId(id) {
  return id.replaceAll("_", "-");
}

function tarotCardRow(card) {
  return `(${[
    sqlString(card.id),
    sqlString(card.name),
    sqlString(card.slug),
    sqlString(card.arcana),
    sqlString(card.suit),
    card.number === null || card.number === undefined ? "null" : Number(card.number),
    sqlString(card.rank),
    sqlString(card.image),
    sqlJSON(card.keywords ?? []),
    sqlJSON(card.upright ?? {}),
    sqlJSON(card.reversed ?? {}),
    sqlString(card.yesNo),
  ].join(", ")})`;
}

function spreadRow(spread) {
  return `(${[
    sqlString(spread.id),
    sqlString(spread.name),
    sqlString(slugFromId(spread.id)),
    sqlString(spread.category),
    sqlString(spread.description),
    Number(spread.cardCount),
    "true", // is_system
  ].join(", ")})`;
}

function positionRows(spread) {
  return spread.positions
    .map(
      (pos) =>
        `(${[sqlString(spread.id), Number(pos.index), sqlString(pos.name), sqlString(pos.description)].join(", ")})`
    )
    .join(",\n  ");
}

const cardValues = TAROT_CARDS.map(tarotCardRow).join(",\n  ");
const spreadValues = DEFAULT_SPREADS.map(spreadRow).join(",\n  ");
const positionValues = DEFAULT_SPREADS.map(positionRows).join(",\n  ");

const sql = `-- OTR — Seed system data (Phase 12 completion, generated by
-- scripts/generate-seed-sql.mjs — JANGAN edit manual, re-generate dari
-- data/tarot-cards.js / data/default-spreads.js kalau datanya berubah)
--
-- Mengisi tarot_cards (78 kartu) + spreads (10 spread MVP, §13) +
-- spread_positions, semuanya is_system=true (public read-only, §46).
-- Dibutuhkan SEBELUM readings/reading_cards bisa di-insert (foreign key).
-- idempotent lewat "on conflict do nothing" — aman dijalankan ulang.

insert into tarot_cards (id, name, slug, arcana, suit, card_number, rank, image_url, keywords, upright, reversed, yes_no)
values
  ${cardValues}
on conflict (id) do nothing;

insert into spreads (id, name, slug, category, description, card_count, is_system)
values
  ${spreadValues}
on conflict (id) do nothing;

insert into spread_positions (spread_id, position_index, name, description)
values
  ${positionValues}
on conflict do nothing;
`;

const outPath = path.join(root, "supabase/migrations/0002_seed_system_data.sql");
await writeFile(outPath, sql, "utf8");
console.log(`Wrote ${outPath}`);
console.log(`  tarot_cards: ${TAROT_CARDS.length} rows`);
console.log(`  spreads: ${DEFAULT_SPREADS.length} rows`);
console.log(`  spread_positions: ${DEFAULT_SPREADS.reduce((n, s) => n + s.positions.length, 0)} rows`);
